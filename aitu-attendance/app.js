const el = id => document.getElementById(id);
let language = "ru";
try { const saved = localStorage.getItem("aitu-language"); if (translations[saved]) language = saved; } catch {}
let mode = "limit";
const number = n => new Intl.NumberFormat(language === "kk" ? "kk-KZ" : language, { maximumFractionDigits: 2 }).format(n);
function valid(ids) { return ids.every(id => el(id).value.trim() !== "" && el(id).checkValidity() && Number.isFinite(el(id).valueAsNumber)); }
function calculate() {
  const t = translations[language];
  const total = el("weekly").valueAsNumber * el("weeks").valueAsNumber;
  const missed = el("missed").valueAsNumber;
  const good = valid(["weekly","weeks","missed","threshold"]) && missed <= total;
  el("limit-error").hidden = good;
  el("limit-result").hidden = !good;
  if (good) {
    const allowed = Math.floor(total * (100 - el("threshold").valueAsNumber) / 100 + 1e-9);
    const remaining = allowed - missed;
    el("remaining").textContent = number(Math.abs(remaining));
    el("result-caption").textContent = t[remaining < 0 ? "over" : "remaining"];
    el("status-text").textContent = t[remaining < 0 ? "exceeded" : remaining === 0 ? "edge" : "ok"];
    el("sessions-total").textContent = number(total);
    el("allowed-total").textContent = number(allowed);
    el("attendance").textContent = number(100 * (total - missed) / total) + "%";
    const used = allowed ? Math.min(100, missed / allowed * 100) : missed ? 100 : 0;
    el("progress-fill").style.width = used + "%";
    const track = document.querySelector(".progress-track");
    track.setAttribute("aria-valuenow", String(used));
    track.setAttribute("aria-label", t.progress);
    el("limit-result").classList.toggle("exceeded", remaining < 0);
  }
  const reverseGood = valid(["held","rate"]);
  el("reverse-error").hidden = reverseGood;
  el("reverse-result").hidden = !reverseGood;
  if (reverseGood) {
    const held = el("held").valueAsNumber;
    const raw = held * (100 - el("rate").valueAsNumber) / 100;
    const estimate = Math.round(raw);
    el("estimated-missed").textContent = "≈ " + number(estimate);
    el("estimated-attended").textContent = number(held - estimate);
    el("raw-missed").textContent = number(raw);
  }
}
function setLanguage(lang) {
  if (!translations[lang]) return;
  language = lang;
  document.documentElement.lang = lang;
  document.title = translations[lang].title;
  document.querySelectorAll("[data-i18n]").forEach(node => { node.textContent = translations[lang][node.dataset.i18n]; });
  el("subject").placeholder = translations[lang].placeholder;
  document.querySelector(".brand").setAttribute("aria-label", translations[lang].home);
  document.querySelectorAll("[data-lang]").forEach(button => button.setAttribute("aria-pressed", String(button.dataset.lang === lang)));
  try { localStorage.setItem("aitu-language", lang); } catch {}
  calculate();
}
function setMode(next) {
  mode = next;
  for (const name of ["limit","reverse"]) {
    el(name + "-panel").hidden = name !== mode;
    el(name + "-tab").setAttribute("aria-selected", String(name === mode));
    el(name + "-tab").tabIndex = name === mode ? 0 : -1;
  }
}
document.querySelectorAll("[data-lang]").forEach(button => button.addEventListener("click", () => setLanguage(button.dataset.lang)));
for (const name of ["limit","reverse"]) {
  el(name + "-tab").addEventListener("click", () => setMode(name));
  el(name + "-tab").addEventListener("keydown", event => {
    if (["ArrowLeft","ArrowRight","Home","End"].includes(event.key)) {
      event.preventDefault();
      setMode(event.key === "Home" ? "limit" : event.key === "End" ? "reverse" : mode === "limit" ? "reverse" : "limit");
      el(mode + "-tab").focus();
    }
  });
}
document.querySelectorAll("input").forEach(input => input.addEventListener("input", calculate));
setMode("limit");
setLanguage(language);
